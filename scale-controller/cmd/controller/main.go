const (
	disableWebhook            = "false"
	disableCardScalingRequest = "false"
	disableCardAlert          = "false"
)

var (
	scheme   = runtime.NewScheme()
	setupLog = ctrl.Log.WithName("setup")
)

type certConfig struct {
	certPath string
	certName string
	certKey  string
}

type flagParams struct {
	metricsAddr          string
	probeAddr            string
	enableLeaderElection bool
	secureMetrics        bool
	webhookCertConfig    certConfig
	metricsCertConfig    certConfig
	enableHTTP2          bool
}

func parseFlags(params *flagParams) {
	flag.StringVar(&params.metricsAddr, "metrics-bind-address", "0", "The address the metrics endpoint binds to. "+
		"Use :8443 for HTTPS or :8080 for HTTP, or leave as 0 to disable the metrics service.")
	flag.StringVar(&params.probeAddr, "health-probe-bind-address", ":8081", "The address the probe endpoint binds to.")
	flag.BoolVar(&params.enableLeaderElection, "leader-elect", false,
		"Enable leader election for controller manager. "+
			"Enabling this will ensure there is only one active controller manager.")
	flag.BoolVar(&params.secureMetrics, "metrics-secure", true,
		"If set, the metrics endpoint is served securely via HTTPS. Use --metrics-secure=false to use HTTP instead.")
	flag.StringVar(&params.webhookCertConfig.certPath, "webhook-cert-path", "", "The directory that contains the webhook certificate.")
	flag.StringVar(&params.webhookCertConfig.certName, "webhook-cert-name", "tls.crt", "The name of the webhook certificate file.")
	flag.StringVar(&params.webhookCertConfig.certKey, "webhook-cert-key", "tls.key", "The name of the webhook key file.")
	flag.StringVar(&params.metricsCertConfig.certPath, "metrics-cert-path", "",
		"The directory that contains the metrics server certificate.")
	flag.StringVar(&params.metricsCertConfig.certName, "metrics-cert-name", "tls.crt", "The name of the metrics server certificate file.")
	flag.StringVar(&params.metricsCertConfig.certKey, "metrics-cert-key", "tls.key", "The name of the metrics server key file.")
	flag.BoolVar(&params.enableHTTP2, "enable-http2", false,
		"If set, HTTP/2 will be enabled for the metrics and webhook servers")
	flag.Parse()
}

//nolint:gochecknoinits // this function is automatically generated by kubebuilder
func init() {
	klog.InitFlags(nil)

	utilruntime.Must(clientgoscheme.AddToScheme(scheme))

	utilruntime.Must(scalev1.AddToScheme(scheme))
	// +kubebuilder:scaffold:scheme
}

func main() {
	if code := run(); code != 0 {
		os.Exit(code)
	}
}

func run() int {
	// parse command line flags
	flags := &flagParams{}
	parseFlags(flags)

	// copy flag values to local variables
	var (
		metricsAddr          = flags.metricsAddr
		probeAddr            = flags.probeAddr
		enableLeaderElection = flags.enableLeaderElection
		secureMetrics        = flags.secureMetrics
		webhookCertPath      = flags.webhookCertConfig.certPath
		webhookCertName      = flags.webhookCertConfig.certName
		webhookCertKey       = flags.webhookCertConfig.certKey
		metricsCertPath      = flags.metricsCertConfig.certPath
		metricsCertName      = flags.metricsCertConfig.certName
		metricsCertKey       = flags.metricsCertConfig.certKey
		enableHTTP2          = flags.enableHTTP2
	)

	var tlsOpts []func(*tls.Config)

	ctrl.SetLogger(textlogger.NewLogger(textlogger.NewConfig()))

	// if the enable-http2 flag is false (the default), http/2 should be disabled
	// due to its vulnerabilities. More specifically, disabling http/2 will
	// prevent from being vulnerable to the HTTP/2 Stream Cancellation and
	// Rapid Reset CVEs. For more information see:
	// - https://github.com/advisories/GHSA-qppj-fm5r-hxr3
	// - https://github.com/advisories/GHSA-4374-p667-p6c8
	disableHTTP2 := func(c *tls.Config) {
		setupLog.Info("disabling http/2")
		c.NextProtos = []string{"http/1.1"}
	}

	if !enableHTTP2 {
		tlsOpts = append(tlsOpts, disableHTTP2)
	}

	webhookTLSOpts := tlsOpts
	// initialize the webhook certificate watcher if a path is provided.
	webhookCertWatcher, err := initializeCertWatcher("webhook", webhookCertPath, webhookCertName, webhookCertKey, &webhookTLSOpts)
	if err != nil {
		setupLog.Error(err, "Failed to initialize webhook certificate watcher")
		return 1
	}

	webhookServer := webhook.NewServer(webhook.Options{
		TLSOpts: webhookTLSOpts,
	})

	// Metrics endpoint is enabled in 'config/default/kustomization.yaml'. The Metrics options configure the server.
	// More info:
	// - https://pkg.go.dev/sigs.k8s.io/controller-runtime@v0.20.4/pkg/metrics/server
	// - https://book.kubebuilder.io/reference/metrics.html
	metricsServerOptions := metricsserver.Options{
		BindAddress:   metricsAddr,
		SecureServing: secureMetrics,
		TLSOpts:       tlsOpts,
	}

	if secureMetrics {
		// FilterProvider is used to protect the metrics endpoint with authn/authz.
		// These configurations ensure that only authorized users and service accounts
		// can access the metrics endpoint. The RBAC are configured in 'config/rbac/kustomization.yaml'. More info:
		// https://pkg.go.dev/sigs.k8s.io/controller-runtime@v0.20.4/pkg/metrics/filters#WithAuthenticationAndAuthorization
		metricsServerOptions.FilterProvider = filters.WithAuthenticationAndAuthorization
	}

	// If the certificate is not specified, controller-runtime will automatically
	// generate self-signed certificates for the metrics server. While convenient for development and testing,
	// this setup is not recommended for production.
	//
	// TODO(user): If you enable certManager, uncomment the following lines:
	// - [METRICS-WITH-CERTS] at config/default/kustomization.yaml to generate and use certificates
	// managed by cert-manager for the metrics server.
	// - [PROMETHEUS-WITH-CERTS] at config/prometheus/kustomization.yaml for TLS certification.

	// initialize the metrics certificate watcher if a path is provided.
	metricsCertWatcher, err := initializeCertWatcher(
		"metrics", metricsCertPath, metricsCertName, metricsCertKey, &metricsServerOptions.TLSOpts)
	if err != nil {
		setupLog.Error(err, "Failed to initialize metrics certificate watcher")
		return 1
	}

	mgr, err := ctrl.NewManager(ctrl.GetConfigOrDie(), ctrl.Options{
		Scheme:                 scheme,
		Metrics:                metricsServerOptions,
		WebhookServer:          webhookServer,
		HealthProbeBindAddress: probeAddr,
		LeaderElection:         enableLeaderElection,
		LeaderElectionID:       "47c39c89.my.domain",
		// LeaderElectionReleaseOnCancel defines if the leader should step down voluntarily
		// when the Manager ends. This requires the binary to immediately end when the
		// Manager is stopped, otherwise, this setting is unsafe. Setting this significantly
		// speeds up voluntary leader transitions as the new leader don't have to wait
		// LeaseDuration time first.
		//
		// In the default scaffold provided, the program ends immediately after
		// the manager stops, so would be fine to enable this option. However,
		// if you are doing or is intended to do any operation such as perform cleanups
		// after the manager stops then its usage might be unsafe.
		// LeaderElectionReleaseOnCancel: true,
	})
	if err != nil {
		setupLog.Error(err, "unable to start manager")
		return 1
	}

	if err := setupWithManager(mgr, metricsCertWatcher, webhookCertWatcher); err != nil {
		setupLog.Error(err, "unable to setup manager")
		return 1
	}

	setupLog.Info("starting manager")
	if err := mgr.Start(ctrl.SetupSignalHandler()); err != nil {
		setupLog.Error(err, "problem running manager")
		return 1
	}

	return 0
}

func getClientHelperOption() (*helperclient.ClientHelperOption, error) {
	// Create ClientHelperOption with ClusterAPI scheme enabled.
	opt := &helperclient.ClientHelperOption{
		SchemeOption: &helperclient.ClientHelperSchemeOption{
			EnableClusterAPI: true,
		},
	}

	// Check provider type from environment variable and enable corresponding scheme.
	providerType, err := utils.GetProviderTypeFromEnv()
	if err != nil {
		return nil, fmt.Errorf("failed to get provider type from environment variable: %w", err)
	}
	switch providerType {
	case utils.ProviderTypeDCI:
		opt.SchemeOption.EnableDCI = true
	case utils.ProviderTypeDocker:
		opt.SchemeOption.EnableDocker = true
	default:
		// This case is only for failsafe
		return nil, fmt.Errorf("provider type(%s) is invalid", providerType)
	}

	return opt, nil
}

func setupWithManagerNodeScalingRequest(mgr ctrl.Manager, clientHelper helperclient.ClientHelper) error {
	// setup NodeScalingRequest controller
	nsrReconciler := (&controller.NodeScalingRequestReconciler{
		Client:       mgr.GetClient(),
		Scheme:       mgr.GetScheme(),
		Recorder:     mgr.GetEventRecorder("nodescalingrequest-controller"),
		ClientHelper: clientHelper,
	})
	if err := nsrReconciler.SetupWithManager(mgr); err != nil {
		return fmt.Errorf("unable to create NodeScalingRequest controller: %w", err)
	}

	// setup NodeScalingRequest webhook
	if os.Getenv("ENABLE_WEBHOOKS") != disableWebhook {
		nsrValidator := &scalewebhookv1.NodeScalingRequestCustomValidator{
			ClientHelper: clientHelper,
		}
		if err := nsrValidator.SetupWithManager(mgr); err != nil {
			return fmt.Errorf("unable to create NodeScalingRequest webhook: %w", err)
		}
	}

	return nil
}

func setupWithManagerCardScalingRequest(mgr ctrl.Manager, clientHelper helperclient.ClientHelper) error {
	if os.Getenv("ENABLE_CARD_SCALING_REQUEST") == disableCardScalingRequest {
		return nil
	}

	// setup CardScalingRequest controller
	if err := (&controller.CardScalingRequestReconciler{
		Client:       mgr.GetClient(),
		Scheme:       mgr.GetScheme(),
		Recorder:     mgr.GetEventRecorder("cardscalingrequest-controller"),
		ClientHelper: clientHelper,
	}).SetupWithManager(mgr); err != nil {
		return fmt.Errorf("unable to create CardScalingRequest controller: %w", err)
	}

	// setup NodeScalingRequest webhook
	if os.Getenv("ENABLE_WEBHOOKS") != disableWebhook {
		csrValidator := &scalewebhookv1.CardScalingRequestCustomValidator{
			ClientHelper: clientHelper,
		}
		if err := csrValidator.SetupWithManager(mgr); err != nil {
			return fmt.Errorf("unable to create CardScalingRequest webhook: %w", err)
		}
	}

	return nil
}

func setupWithManagerCardAlert(mgr ctrl.Manager, clientHelper helperclient.ClientHelper) error {
	if os.Getenv("ENABLE_CARD_ALERT") == disableCardAlert {
		return nil
	}

	// setup CardAlert controller
	if err := (&controller.CardAlertReconciler{
		Client:       mgr.GetClient(),
		Scheme:       mgr.GetScheme(),
		Recorder:     mgr.GetEventRecorder("cardalert-controller"),
		ClientHelper: clientHelper,
	}).SetupWithManager(mgr); err != nil {
		return fmt.Errorf("unable to create CardAlert controller: %w", err)
	}

	return nil
}

func setupWithManager(mgr ctrl.Manager, metricsCertWatcher, webhookCertWatcher *certwatcher.CertWatcher) error {
	// get client helper option
	clientHelperOption, err := getClientHelperOption()
	if err != nil {
		return fmt.Errorf("failed to get client helper option: %w", err)
	}
	// create management cluster client helper
	clientHelper, err := helperclient.NewClientHelper(mgr.GetClient(), clientHelperOption)
	if err != nil {
		return fmt.Errorf("failed to create management cluster client helper: %w", err)
	}
	// setup NodeScalingRequest controller and webhook
	if err := setupWithManagerNodeScalingRequest(mgr, clientHelper); err != nil {
		return fmt.Errorf("failed to setup NodeScalingRequest with manager: %w", err)
	}
	// setup CardScalingRequest controller
	if err := setupWithManagerCardScalingRequest(mgr, clientHelper); err != nil {
		return fmt.Errorf("failed to setup CardScalingRequest with manager: %w", err)
	}
	// setup CardAlert controller
	if err := setupWithManagerCardAlert(mgr, clientHelper); err != nil {
		return fmt.Errorf("failed to setup CardAlert with manager: %w", err)
	}

	// +kubebuilder:scaffold:builder

	if metricsCertWatcher != nil {
		setupLog.Info("Adding metrics certificate watcher to manager")
		if err := mgr.Add(metricsCertWatcher); err != nil {
			return fmt.Errorf("unable to add metrics certificate watcher to manager: %w", err)
		}
	}

	if webhookCertWatcher != nil {
		setupLog.Info("Adding webhook certificate watcher to manager")
		if err := mgr.Add(webhookCertWatcher); err != nil {
			return fmt.Errorf("unable to add webhook certificate watcher to manager: %w", err)
		}
	}

	if err := mgr.AddHealthzCheck("healthz", healthz.Ping); err != nil {
		return fmt.Errorf("unable to set up health check: %w", err)
	}
	if err := mgr.AddReadyzCheck("readyz", healthz.Ping); err != nil {
		return fmt.Errorf("unable to set up ready check: %w", err)
	}

	return nil
}

// initializeCertWatcher initializes a certificate watcher for the given certificate type if path is provided.
// If certPath is empty, it returns nil without error.
func initializeCertWatcher(certType, certPath, certName, certKey string, tlsOpts *[]func(*tls.Config)) (*certwatcher.CertWatcher, error) {
	var certWatcher *certwatcher.CertWatcher

	if certPath != "" {
		setupLog.Info("Initializing "+certType+"certificate watcher using provided certificates",
			certType+"-cert-path", certPath, certType+"-cert-name", certName, certType+"-cert-key", certKey)

		var err error
		certWatcher, err = certwatcher.New(
			filepath.Join(certPath, certName),
			filepath.Join(certPath, certKey),
		)
		if err != nil {
			return nil, fmt.Errorf("failed to initialize "+certType+" certificate watcher: %w", err)
		}

		*tlsOpts = append(*tlsOpts, func(config *tls.Config) {
			config.GetCertificate = certWatcher.GetCertificate
		})
	}
	return certWatcher, nil
}
