func TestControllers(t *testing.T) {
	RegisterFailHandler(Fail)

	isDockerTestSkip = os.Getenv("ENV_DOCKER_PROVIDER_ENABLE") != "true"

	suiteConfig, reporterConfig := GinkgoConfiguration()
	if isDockerTestSkip {
		originalLabelFilter := suiteConfig.LabelFilter
		if originalLabelFilter != "" {
			suiteConfig.LabelFilter = fmt.Sprintf("(%s) && !docker", originalLabelFilter)
		} else {
			suiteConfig.LabelFilter = "!docker"
		}
	}

	RunSpecs(t, "Controller Suite", suiteConfig, reporterConfig)
}

var _ = BeforeSuite(func() {
	var err error

	log.SetLogger(zap.New(zap.WriteTo(GinkgoWriter), zap.UseDevMode(true)))
	ctx, cancel = context.WithCancel(context.TODO())

	crdsInManagementCluster := []*apiextensionsv1.CustomResourceDefinition{
		testutils.NewCustomResourceDefinition("Machine", "machines", capiv1.GroupVersion),
		testutils.NewCustomResourceDefinition("MachineSet", "machinesets", capiv1.GroupVersion),
		testutils.NewCustomResourceDefinition("MachineDeployment", "machinedeployments", capiv1.GroupVersion),
		testutils.NewCustomResourceDefinition("DCIMachine", "dcimachines", capdv1.GroupVersion),
		testutils.NewCustomResourceDefinition("DCIMachineTemplate", "dcimachinetemplates", capdv1.GroupVersion),
		testutils.NewCustomResourceDefinition("LogicalServer", "logicalservers", rpmv1.GroupVersion),
		testutils.NewCustomResourceDefinition("MachineAlert", "machinealerts", rpmv1.GroupVersion),
	}

	By("adding scheme for additional packages", func() {
		Expect(scalev1.AddToScheme(scheme.Scheme)).NotTo(HaveOccurred())
		Expect(rpmv1.AddToScheme(scheme.Scheme)).NotTo(HaveOccurred())
		Expect(capdv1.AddToScheme(scheme.Scheme)).NotTo(HaveOccurred())
		Expect(capiv1.AddToScheme(scheme.Scheme)).NotTo(HaveOccurred())
	})

	if !isDockerTestSkip {
		crdsInManagementCluster = append(crdsInManagementCluster,
			testutils.NewCustomResourceDefinition("DockerMachine", "dockermachines", capdockerv1.GroupVersion),
			testutils.NewCustomResourceDefinition("DockerMachineTemplate", "dockermachinetemplates", capdockerv1.GroupVersion),
		)
		Expect(capdockerv1.AddToScheme(scheme.Scheme)).NotTo(HaveOccurred())
	}

	// +kubebuilder:scaffold:scheme

	By("bootstrapping test environment", func() {
		apiServer := &envtest.APIServer{}
		apiServer.Configure().Append(
			"runtime-config", "resource.k8s.io/v1beta2=true", // enable DeviceTaintRule CRD
		)
		testEnvWorkload = &envtest.Environment{
			ControlPlane: envtest.ControlPlane{
				APIServer: apiServer,
			},
			CRDDirectoryPaths:     []string{filepath.Join("..", "..", "config", "crd", "bases")},
			ErrorIfCRDPathMissing: true,
		}
		testEnvManagement = &envtest.Environment{
			CRDs:                  crdsInManagementCluster,
			ErrorIfCRDPathMissing: true,
		}

		// Retrieve the first found binary directory to allow running tests from IDEs
		if binDir := getFirstFoundEnvTestBinaryDir(); binDir != "" {
			testEnvWorkload.BinaryAssetsDirectory = binDir
			testEnvManagement.BinaryAssetsDirectory = binDir
		}

		// cfg is defined in this file globally.
		cfgWorkload, err = testEnvWorkload.Start()
		Expect(err).NotTo(HaveOccurred())
		cfgManagement, err = testEnvManagement.Start()
		Expect(err).NotTo(HaveOccurred())

		k8sClientWorkload, err = client.New(cfgWorkload, client.Options{Scheme: scheme.Scheme})
		Expect(err).NotTo(HaveOccurred())
		k8sClientManagement, err = client.New(cfgManagement, client.Options{Scheme: scheme.Scheme})
		Expect(err).NotTo(HaveOccurred())
	})

	By("creating the kubeconfig file for management cluster", func() {
		kubeconfig := api.NewConfig()
		contextName := "management-cluster-context"
		clusterName := "management-cluster"
		userName := "scale-controller-sa"
		kubeconfig.Clusters[clusterName] = &api.Cluster{
			Server:                   cfgManagement.Host,
			CertificateAuthorityData: cfgManagement.CAData,
			InsecureSkipTLSVerify:    cfgManagement.Insecure,
		}
		kubeconfig.Contexts[contextName] = &api.Context{
			Cluster:  clusterName,
			AuthInfo: userName,
		}
		kubeconfig.AuthInfos[userName] = &api.AuthInfo{
			Token:                 cfgManagement.BearerToken,
			ClientCertificateData: cfgManagement.CertData,
			ClientKeyData:         cfgManagement.KeyData,
			Username:              cfgManagement.Username,
			Password:              cfgManagement.Password,
		}
		kubeconfig.CurrentContext = contextName

		tmpFile, err := os.CreateTemp("", "temp-envtest-*.kubeconfig")
		Expect(err).NotTo(HaveOccurred())
		defer Expect(tmpFile.Close()).NotTo(HaveOccurred())
		kubeconfigPathManagement = tmpFile.Name()
		Expect(clientcmd.WriteToFile(*kubeconfig, kubeconfigPathManagement)).NotTo(HaveOccurred())
		Expect(os.Setenv("MANAGEMENT_KUBECONFIG", kubeconfigPathManagement)).NotTo(HaveOccurred())
	})

	By("creating the resource Namespace for resource-pool-manager@Management", func() {
		ns := &corev1.Namespace{ObjectMeta: metav1.ObjectMeta{Name: rpmNamespace}}
		Expect(k8sClientManagement.Create(ctx, ns)).To(Succeed())
	})
	By("creating the resource Namespace@Management", func() {
		ns := &corev1.Namespace{ObjectMeta: metav1.ObjectMeta{Name: testNamespace}}
		Expect(k8sClientManagement.Create(ctx, ns)).To(Succeed())
	})
	By("creating the resource Namespace@Workload", func() {
		ns := &corev1.Namespace{ObjectMeta: metav1.ObjectMeta{Name: testNamespace}}
		Expect(k8sClientWorkload.Create(ctx, ns)).To(Succeed())
	})
})

var _ = AfterSuite(func() {
	By("tearing down the test environment")
	cancel()
	By("deleting the kubeconfig file("+kubeconfigPathManagement+") for management cluster", func() {
		Expect(kubeconfigPathManagement).NotTo(Equal(""))
		Expect(os.Remove(kubeconfigPathManagement)).NotTo(HaveOccurred())
	})
	By("stopping running server", func() {
		Expect(testEnvWorkload).NotTo(BeNil())
		Expect(testEnvWorkload.Stop()).NotTo(HaveOccurred())
	})
	By("stopping running server for management cluster", func() {
		Expect(testEnvManagement).NotTo(BeNil())
		Expect(testEnvManagement.Stop()).NotTo(HaveOccurred())
	})
})

// getFirstFoundEnvTestBinaryDir locates the first binary in the specified path.
// ENVTEST-based tests depend on specific binaries, usually located in paths set by
// controller-runtime. When running tests directly (e.g., via an IDE) without using
// Makefile targets, the 'BinaryAssetsDirectory' must be explicitly configured.
//
// This function streamlines the process by finding the required binaries, similar to
// setting the 'KUBEBUILDER_ASSETS' environment variable. To ensure the binaries are
// properly set up, run 'make setup-envtest' beforehand.
func getFirstFoundEnvTestBinaryDir() string {
	basePath := filepath.Join("..", "..", "bin", "k8s")
	entries, err := os.ReadDir(basePath)
	if err != nil {
		log.Log.Error(err, "Failed to read directory", "path", basePath)
		return ""
	}
	for _, entry := range entries {
		if entry.IsDir() {
			return filepath.Join(basePath, entry.Name())
		}
	}
	return ""
}
